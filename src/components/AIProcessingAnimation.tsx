// react-native-svg elements can be made animatable with Animated.createAnimatedComponent.
const AnimatedG = Animated.createAnimatedComponent(G);

const KEY_TIMES = [0, 0.249875, 0.49975, 0.749625, 0.9995, 1];

export default function AIProcessingAnimation({
  width = 260,
  height = 260,
  style,
}: AIProcessingAnimationProps) {
  // One shared native timeline drives every layer.
  const progress = useRef(new Animated.Value(0)).current;

  useEffect(() => {
    const animation = Animated.loop(
      Animated.timing(progress, {
        toValue: 1,
        duration: DURATION,
        easing: Easing.linear,
        useNativeDriver: true,
        isInteraction: false,
      })
    );

    animation.start();

    return () => {
      animation.stop();
      progress.stopAnimation();
    };
  }, [progress]);

  return (
    <Animated.View
      style={[
        {
          width,
          height,
          justifyContent: "center",
          alignItems: "center",
        },
        style,
      ]}
    >
      <View
        pointerEvents="none"
        style={{
          width: "100%",
          height: "100%",
        }}
      >
        <Svg
          width="100%"
          height="100%"
          viewBox="0 0 340 340"
          fill="none"
        >
          <Defs>
            <LinearGradient
              id="aiProcessingGradient"
              x1="70"
              y1="40"
              x2="280"
              y2="300"
              gradientUnits="userSpaceOnUse"
            >
              <Stop offset="0%" stopColor={COLORS.pink} />
              <Stop offset="25%" stopColor={COLORS.purple} />
              <Stop offset="50%" stopColor={COLORS.blue} />
              <Stop offset="75%" stopColor={COLORS.teal} />
              <Stop offset="100%" stopColor={COLORS.green} />
            </LinearGradient>
          </Defs>

          {LAYERS.map((layer, index) => {
            const translateX = progress.interpolate({
              inputRange: KEY_TIMES,
              outputRange: layer.tx as any,
            });

            const translateY = progress.interpolate({
              inputRange: KEY_TIMES,
              outputRange: layer.ty as any,
            });

            const rotation = progress.interpolate({
              inputRange: KEY_TIMES,
              outputRange: layer.rot.map((value) => `${value}deg`),
            });

            /*
             * This preserves the original SVG transform structure:
             *
             * translate(animatedPosition)
             *   rotate(animatedAngle)
             *     translate(originalPathOffset)
             *       path
             *
             * The path itself is intentionally NOT changed.
             */
            return (
              <AnimatedG
                key={`ai-layer-${index}`}
                opacity={layer.opacity}
                transform={[
                  { translateX },
                  { translateY },
                  { rotate: rotation },
                  { translateX: Number(layer.inner[0]) },
                  { translateY: Number(layer.inner[1]) },
                ] as any}
              >
                <Path
                  d={layer.d}
                  stroke="url(#aiProcessingGradient)"
                  strokeWidth={1}
                  fill="none"
                  strokeLinecap="round"
                  opacity={0.95}
                />
              </AnimatedG>
            );
          })}

        </Svg>
      </View>
    </Animated.View>
  );
}
